#!/usr/bin/env bash
# Build the in-browser Lean runtime for Leandoku.
#
#   wasm/build-runtime.sh <work dir> <out dir>
#
# Needs: emsdk 3.1.44 activated (emcc on PATH), clang, cmake, ccache,
# gcc-multilib/g++-multilib, libuv1-dev:i386, pkgconf:i386, and elan with the
# toolchain from lean/lean-toolchain.
#
# Lean is built in two stages, like Lean's own (disabled) wasm CI job:
#   stage0  a native 32-bit Lean (wasm32 has 4-byte pointers, so the .olean
#           files the browser loads must come from a 32-bit Lean);
#   stage1  Lean's libraries compiled to WebAssembly by emscripten, and
#           32-bit .olean files compiled by stage0.
# Our patch makes the wasm build single-threaded so the page needs no
# cross-origin isolation (GitHub Pages cannot send COOP/COEP headers).
#
# Then the bridge's generated C (Lean's C output is portable, so the native
# toolchain's `lake build` C is used as-is) is linked against stage1 into
# leandoku-bridge.{js,wasm}, and Init's .olean + .ir files are packed.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
work="$(mkdir -p "$1" && cd "$1" && pwd)"
out="$(mkdir -p "$2" && cd "$2" && pwd)"
jobs="${JOBS:-$(nproc)}"

toolchain="$(cat "$root/lean/lean-toolchain")"   # leanprover/lean4:v4.24.0
tag="${toolchain#*:}"

src="$work/lean4"
if [ ! -d "$src" ]; then
  git clone -q --depth 1 --branch "$tag" https://github.com/leanprover/lean4 "$src"
  git -C "$src" apply "$here/lean-emscripten.patch"
fi

build="$work/build"
mkdir -p "$build"
if [ ! -f "$build/CMakeCache.txt" ]; then
  (cd "$build" && emcmake cmake "$src" \
    -DCMAKE_BUILD_TYPE=Release -DCCACHE=ON -DLEAN_INSTALL_SUFFIX=-linux_wasm32 \
    -DUSE_GMP=OFF -DMMAP=OFF -DMULTI_THREAD=OFF \
    -DSTAGE0_USE_GMP=OFF -DSTAGE0_MMAP=OFF \
    -DSTAGE0_CMAKE_C_COMPILER=clang -DSTAGE0_CMAKE_CXX_COMPILER=clang++ \
    -DSTAGE0_CMAKE_TOOLCHAIN_FILE= -DSTAGE0_CMAKE_EXECUTABLE_SUFFIX= \
    -DSTAGE0_CMAKE_AR=/usr/bin/ar -DSTAGE0_CMAKE_RANLIB=/usr/bin/ranlib \
    -DSTAGE0_CMAKE_LIBRARY_PATH=/usr/lib/i386-linux-gnu/ \
    -DSTAGE0_PKG_CONFIG_EXECUTABLE=/usr/bin/i386-linux-gnu-pkg-config \
    "-DSTAGE0_LEAN_EXTRA_CXX_FLAGS=-m32" "-DSTAGE0_LEANC_OPTS=-m32" \
    -DUSE_MIMALLOC=ON -DSTAGE1_USE_MIMALLOC=OFF \
    "-DSTAGE1_CMAKE_TOOLCHAIN_FILE=$EMSDK/upstream/emscripten/cmake/Modules/Platform/Emscripten.cmake")
fi
# See emcc-capped.sh: some files need too much memory at -O3.
# The stage1 build also tries to build `leanc` for wasm, whose source the
# emscripten configuration does not generate; we do not need it, so the
# build may report that failure. We check for what we need instead.
LEAN_CC="$here/emcc-capped.sh" make -C "$build" -j"$jobs" stage1 || true
stage1="$build/stage1"
for lib in libInit.a libStd.a libLean.a libleanrt.a libleancpp.a Init.olean; do
  [ -e "$stage1/lib/lean/$lib" ] || { echo "stage1 did not produce $lib" >&2; exit 1; }
done
objs="$work/objs"
mkdir -p "$objs"

# Bridge C, generated by the native toolchain (Lean's C output is portable).
(cd "$root/lean" && lake build Bridge)
ir="$root/lean/.lake/build/ir"
for c in "$ir/Bridge.c" "$ir"/Bridge/*.c; do
  emcc -O2 -fwasm-exceptions -DLEAN_EMSCRIPTEN -I "$stage1/include" -c "$c" -o "$objs/$(basename "$c" .c).o"
done

# Symbol table for lean_emscripten_lookup_symbol (see gen-symbols.py).
LLVM_NM="$EMSDK/upstream/bin/llvm-nm" python3 "$here/gen-symbols.py" "$objs/symbols.c" \
  --c-dir "$stage1/lib/temp" --c-dir "$ir" --exclude 'Lean/Server/Test/' \
  --lib "$stage1/lib/lean/libInit.a" --lib "$stage1/lib/lean/libStd.a" --lib "$stage1/lib/lean/libLean.a" \
  $(for o in "$objs"/[A-Z]*.o; do echo --lib "$o"; done)

emcc -O2 -fwasm-exceptions -s ALLOW_MEMORY_GROWTH=1 -s INITIAL_MEMORY=256MB \
  -s STACK_SIZE=8MB -s MODULARIZE=1 -s EXPORT_ES6=1 -s ENVIRONMENT=web,worker,node \
  -s EXPORTED_FUNCTIONS=_malloc,_free \
  -s EXPORTED_RUNTIME_METHODS=ccall,UTF8ToString,FS \
  -DLEAN_EMSCRIPTEN -I "$stage1/include" \
  "$objs"/[A-Z]*.o "$objs/symbols.c" "$here/glue.c" "$here/stubs.c" \
  -L "$stage1/lib/lean" -lLean -lStd -lInit -lleanrt -lleancpp \
  "$stage1/libuv/src/libuv/libuv.a" -lm \
  -o "$out/leandoku-bridge.js"

node --experimental-strip-types "$root/wasm/pack-library.ts" "$stage1/lib/lean" "$out/library.ldpk" Init
ls -la "$out"
