#!/usr/bin/env python3
"""Write the C symbol table behind lean_emscripten_lookup_symbol.

Lean finds compiled code at run time by symbol name: module initializers
when importing, and compiled definitions when it evaluates declarations from
the environment (parsers, elaborators, attributes). Natively that is dlsym; a
static wasm module has none (see lean-emscripten.patch), so we list every
exported definition with its real C prototype, taken from the C files Lean
generated, and keep only names the archives actually define.

    gen-symbols.py <out.c> --c-dir DIR ... --lib LIB.a ... [--exclude REGEX]

--exclude skips definitions from matching C files. Lean/Server/Test/Runner.c
has to be compiled at -O0 (see emcc-capped.sh), which leaves a function with
more locals than browsers accept; nothing references it unless this table
does, so it is left out.
"""
import argparse, os, re, subprocess, sys

ap = argparse.ArgumentParser()
ap.add_argument('out')
ap.add_argument('--c-dir', action='append', default=[])
ap.add_argument('--lib', action='append', default=[])
ap.add_argument('--exclude', action='append', default=[])
args = ap.parse_args()

defined = set()
for lib in args.lib:
    nm = subprocess.run([os.environ.get('LLVM_NM', 'llvm-nm'), '--defined-only', lib], capture_output=True, text=True, check=True).stdout
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ('T', 'D', 'B'):
            defined.add(parts[2])

decl = re.compile(r'^LEAN_EXPORT ([^()]*?[\s*])((?:l|initialize)_\w+)(\(.*\))?;$')
protos = {}
for d in args.c_dir:
    for root, _, files in os.walk(d):
        for f in files:
            path = os.path.join(root, f)
            if not f.endswith('.c') or any(re.search(x, path) for x in args.exclude):
                continue
            with open(path, encoding='utf-8', errors='replace') as fh:
                for line in fh:
                    if not line.startswith('LEAN_EXPORT'):
                        continue
                    m = decl.match(line.rstrip('\n'))
                    if m and m.group(2) in defined and m.group(2) not in protos:
                        protos[m.group(2)] = (m.group(1).strip(), m.group(3))

names = sorted(protos)
with open(args.out, 'w') as out:
    out.write('/* Generated by wasm/gen-symbols.py. */\n#include <lean/lean.h>\n#include <stdlib.h>\n#include <string.h>\n')
    for n in names:
        ret, params = protos[n]
        out.write(f'extern {ret} {n}{params or ""};\n')
    out.write('static const struct entry { const char *name; void *addr; } table[] = {\n')
    for n in names:
        out.write(f'  {{"{n}", (void *)&{n}}},\n')
    out.write('};\n')
    out.write('''static int cmp(const void *key, const void *e) {
  return strcmp((const char *)key, ((const struct entry *)e)->name);
}
void *lean_emscripten_lookup_symbol(const char *sym) {
  const struct entry *hit = bsearch(sym, table, sizeof table / sizeof table[0], sizeof table[0], cmp);
  return hit ? hit->addr : NULL;
}
''')
print(f'{len(names)} symbols -> {args.out}', file=sys.stderr)
