// Turns policy.json (from train.js) into the two files the game reads:
//   public/no_thanks/bot-policy.txt     practice bots, in the browser
//   tools/supabase/nothanks_policy.sql  online bots, in the database (run it after nothanks_schema.sql)
// One character per situation bucket: '.' = never seen in training, otherwise P(take) * 63 in base64url digits.
'use strict';
const fs = require('fs'), path = require('path');
const ABC = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
const pol = require('./policy.json');
const s = pol.map(p => p < 0 ? '.' : ABC[Math.round(p / 100 * 63)]).join('');
const root = path.join(__dirname, '..', '..');
fs.writeFileSync(path.join(root, 'public/no_thanks/bot-policy.txt'), s + '\n');
fs.writeFileSync(path.join(root, 'tools/supabase/nothanks_policy.sql'),
`-- No Thanks! bots' policy, generated by tools/no_thanks_cfr/export.js (don't edit by hand). Run after nothanks_schema.sql.
insert into public.nothanks_policy (id, policy) values (1, '${s}')
on conflict (id) do update set policy = excluded.policy;
`);
console.log('wrote', s.length, 'buckets');
