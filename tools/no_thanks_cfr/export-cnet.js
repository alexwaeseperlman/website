// Ships one or more cnet3 nets (deep.cpp's CNet: two 1D convs over the card line, a readout at the card in play, then
// pnet's pooling and trunk); the bot averages their outputs. Stores each layer part as 16-bit integers with one scale
// (8 bits cost ~1 point in deep vs), one net after another, and writes public/no_thanks/bot-net.json for the page and
// tools/supabase/nothanks_net.sql, which loads the same bytes into the database's nothanks_net table. Also writes
// <in>-deq.json for each net, the float weights the bytes decode to (for deep vs / check-cnet.js). Nets trained with
// PPO (deep ppo, "head":"logit") output a take logit and a value instead of regrets; the nets must all be one kind.
//   node export-cnet.js abl/deep-cnet3-cnet3-adv.json abl/deep-cnet3-cnet3b-adv.json
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '../..'), out = path.join(root, 'public/no_thanks/bot-net.json');
const files = process.argv.slice(2), nets = files.map(f => JSON.parse(fs.readFileSync(f, 'utf8')));
for (const W of nets) if (W.arch !== 'cnet3' || W.out !== 2) throw new Error('want cnet3 nets, got ' + W.arch);
const logit = nets[0].head === 'logit';
if (nets.some(W => (W.head === 'logit') !== logit)) throw new Error('mixing PPO and CFR nets');
// [inputs x outputs] of every layer, in the order of the weights: conv1 (4 ch x kernel 5 -> 12), conv2 (12 x 3 -> 12),
// encoder 106 -> 32, trunk 131 -> 64 -> 64 -> 2. Each is weights (row per output) then biases.
const LAYERS = [[20, 12], [36, 12], [106, 32], [131, 64], [64, 64], [64, 2]];
const segs = []; let o = 0;
for (const W of nets){ const st0 = o; for (const [i, n] of LAYERS) for (const len of [i * n, n]){ segs.push([o, len]); o += len; }
  if (o - st0 !== W.p.length) throw new Error(`${W.p.length} weights, layout has ${o - st0}`); }
const all = nets.flatMap(W => W.p);
const bytes = new Int16Array(o), scales = [], deq = new Array(o);
for (const [st, len] of segs){
  let m = 0; for (let k = 0; k < len; k++) m = Math.max(m, Math.abs(all[st + k]));
  const s = +(m / 32767 || 1).toPrecision(6); scales.push(s);
  for (let k = 0; k < len; k++){ bytes[st + k] = Math.round(all[st + k] / s); deq[st + k] = bytes[st + k] * s; }
}
const q = Buffer.from(bytes.buffer).toString('base64');   // little-endian int16
fs.writeFileSync(out, JSON.stringify({ arch: 'cnet3', out: 2, ...(logit && { head: 'logit' }), nets: nets.length, scales, q }));
const N = o / nets.length;
files.forEach((f, i) => fs.writeFileSync(f.replace('.json', '-deq.json'), JSON.stringify({ arch: 'cnet3', out: 2, drop: '', ...(logit && { head: 'logit' }), p: deq.slice(i * N, (i + 1) * N) })));
fs.writeFileSync(path.join(root, 'tools/supabase/nothanks_net.sql'),
`-- No Thanks! neural-net bot weights, generated by tools/no_thanks_cfr/export-cnet.js (don't edit by hand).
-- Run after nothanks_schema.sql. The bytes are the same as public/no_thanks/bot-net.json (little-endian int16s).
insert into public.nothanks_net (id, scales, q, logit) values (1, '{${scales.join(',')}}', decode('${q}', 'base64'), ${logit})
on conflict (id) do update set scales = excluded.scales, q = excluded.q, logit = excluded.logit;
update public.nothanks_net n set w = (
  select array_agg((get_byte(n.q, 2 * i) + 256 * get_byte(n.q, 2 * i + 1) - case when get_byte(n.q, 2 * i + 1) > 127 then 65536 else 0 end) * n.scales[si] order by i)
  from (values ${segs.map(([st, len], i) => `(${i + 1},${st},${len})`).join(',')}) seg(si, st, len), generate_series(st, st + len - 1) i)
where id = 1;
`);
console.log(nets.length, 'nets,', 'weights', o, 'base64 chars', q.length, '-> bot-net.json, nothanks_net.sql');
