// Ships a cnet3 net (deep.cpp's CNet: two 1D convs over the card line, a readout at the card in play, then pnet's
// pooling and trunk): stores each layer part as 16-bit integers with one scale (8 bits cost it ~1 point in deep vs), writes public/no_thanks/bot-net.json for
// the page and tools/supabase/nothanks_net.sql, which loads the same bytes into the database's nothanks_net table.
// Also writes <in>-deq.json, the float weights the bytes decode to (for deep vs / check-cnet.js).
//   node export-cnet.js abl/deep-cnet3-cnet3b-adv.json
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '../..'), out = path.join(root, 'public/no_thanks/bot-net.json');
const W = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
if (W.arch !== 'cnet3') throw new Error('want a cnet3 net, got ' + W.arch);
// [inputs x outputs] of every layer, in the order of the weights: conv1 (4 ch x kernel 5 -> 12), conv2 (12 x 3 -> 12),
// encoder 106 -> 32, trunk 131 -> 64 -> 64 -> 2. Each is weights (row per output) then biases.
const LAYERS = [[20, 12], [36, 12], [106, 32], [131, 64], [64, 64], [64, W.out]];
const segs = []; let o = 0; for (const [i, n] of LAYERS) for (const len of [i * n, n]){ segs.push([o, len]); o += len; }
if (o !== W.p.length) throw new Error(`${W.p.length} weights, layout has ${o}`);
const bytes = new Int16Array(o), scales = [], deq = new Array(o);
for (const [st, len] of segs){
  let m = 0; for (let k = 0; k < len; k++) m = Math.max(m, Math.abs(W.p[st + k]));
  const s = +(m / 32767 || 1).toPrecision(6); scales.push(s);
  for (let k = 0; k < len; k++){ bytes[st + k] = Math.round(W.p[st + k] / s); deq[st + k] = bytes[st + k] * s; }
}
const q = Buffer.from(bytes.buffer).toString('base64');   // little-endian int16
fs.writeFileSync(out, JSON.stringify({ arch: W.arch, out: W.out, scales, q }));
fs.writeFileSync(process.argv[2].replace('.json', '-deq.json'), JSON.stringify({ arch: W.arch, out: W.out, drop: '', p: deq }));
fs.writeFileSync(path.join(root, 'tools/supabase/nothanks_net.sql'),
`-- No Thanks! neural-net bot weights, generated by tools/no_thanks_cfr/export-cnet.js (don't edit by hand).
-- Run after nothanks_schema.sql. The bytes are the same as public/no_thanks/bot-net.json (little-endian int16s).
insert into public.nothanks_net (id, scales, q) values (1, '{${scales.join(',')}}', decode('${q}', 'base64'))
on conflict (id) do update set scales = excluded.scales, q = excluded.q;
update public.nothanks_net n set w = (
  select array_agg((get_byte(n.q, 2 * i) + 256 * get_byte(n.q, 2 * i + 1) - case when get_byte(n.q, 2 * i + 1) > 127 then 65536 else 0 end) * n.scales[si] order by i)
  from (values ${segs.map(([st, len], i) => `(${i + 1},${st},${len})`).join(',')}) seg(si, st, len), generate_series(st, st + len - 1) i)
where id = 1;
`);
console.log('weights', o, 'base64 chars', q.length, '-> bot-net.json, nothanks_net.sql');
