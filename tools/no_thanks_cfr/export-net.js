// Ships a trained structured net: quantizes it (quant.js) into public/no_thanks/bot-net.json for the page, and writes
// tools/supabase/nothanks_net.sql, which loads the same bytes into the database's nothanks_net table.
//   node export-net.js deep-struct-adv.json
'use strict';
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const root = path.join(__dirname, '../..'), out = path.join(root, 'public/no_thanks/bot-net.json');
execFileSync('node', [path.join(__dirname, 'quant.js'), path.resolve(process.argv[2]), out], { stdio: 'inherit' });
fs.unlinkSync(out.replace('.json', '-deq.json'));
const j = JSON.parse(fs.readFileSync(out, 'utf8'));
const layers = [[16, 32], [32, 32], [108, 64], [64, 64], [64, 2]], segs = [];
let o = 0; for (const [i, n] of layers) for (const len of [i * n, n]){ segs.push(`(${segs.length + 1},${o},${len})`); o += len; }
fs.writeFileSync(path.join(root, 'tools/supabase/nothanks_net.sql'),
`-- No Thanks! neural-net bot weights, generated by tools/no_thanks_cfr/export-net.js (don't edit by hand).
-- Run after nothanks_schema.sql. The bytes are the same as public/no_thanks/bot-net.json.
insert into public.nothanks_net (id, scales, q) values (1, '{${j.scales.join(',')}}', decode('${j.q}', 'base64'))
on conflict (id) do update set scales = excluded.scales, q = excluded.q;
update public.nothanks_net n set w = (
  select array_agg((case when get_byte(n.q, i) > 127 then get_byte(n.q, i) - 256 else get_byte(n.q, i) end) * n.scales[si] order by i)
  from (values ${segs.join(',')}) seg(si, st, len), generate_series(st, st + len - 1) i)
where id = 1;
`);
console.log('wrote', out, 'and nothanks_net.sql');
